import os, sys, unittest
sys.path.insert(0, os.path.join(os.path.dirname(__file__), ".."))
import photos

CFG = {"minLongSide": 1000, "minShortSide": 600, "trustedSources": ["nasa", "wikimedia"]}
R = lambda **k: {"license": "cc0", "width": 3000, "height": 2000, "title": "Hubble Space Telescope in orbit", "source": "flickr", "tags": [], **k}


class Photos(unittest.TestCase):
    def test_only_cc0_and_pdm(self):
        self.assertEqual(photos.candidates([R(license="by"), R(license="by-nc"), R(license="pdm")], CFG, "Hubble telescope")[0]["license"], "pdm")
        self.assertEqual(photos.candidates([R(license="by")], CFG, "Hubble telescope"), [])

    def test_ai_and_wrong_subject_and_small_are_left_out(self):
        self.assertEqual(photos.candidates([R(title="Hubble Space Telescope, generated by Midjourney")], CFG, "Hubble Space Telescope"), [])
        self.assertEqual(photos.candidates([R(title="A galaxy group, annotated", tags=[{"name": "hubble"}])], CFG, "Hubble Space Telescope"), [])
        self.assertEqual(photos.candidates([R(width=800, height=500)], CFG, "Hubble Space Telescope"), [])

    def test_trusted_source_first(self):
        got = photos.candidates([R(width=6000, height=4000), R(source="wikimedia", width=2000, height=1500)], CFG, "Hubble Space Telescope")
        self.assertEqual(got[0]["source"], "wikimedia")

    def test_real_size_is_read_from_the_file(self):
        # minimal JPEG: SOI, SOF0 (height 300, width 400), then padding
        jpg = b"\xff\xd8\xff\xc0\x00\x11\x08\x01\x2c\x01\x90\x03" + b"\x00" * 20
        self.assertEqual(photos.jpeg_size(jpg), (400, 300))


if __name__ == "__main__":
    unittest.main()


class TestSrcSafety(unittest.TestCase):
    def test_src_pattern_rejects_paths(self):
        for bad in ("../x", "/tmp/x", "a/b", "A", ""):
            self.assertFalse(photos.SRC_OK.match(bad), bad)
        self.assertTrue(photos.SRC_OK.match("hubble-1"))
